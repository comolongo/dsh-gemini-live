#!/usr/bin/env node
/**
 * Render the prebuilt Gemini voices into `docs/voices/`, and write the page that plays them.
 *
 * The page exists because a voice name is not a sound: choosing one from a table is guesswork, and the
 * alternative — auditioning inside AI Studio — needs a key selected in a web UI rather than the one this
 * repository already holds. This renders every voice with the **same** text, so the only difference a
 * listener hears is the voice.
 *
 * `gemini-3.8-flash-tts` renders them; the Live session uses the same voice IDs, so the timbre matches
 * although a live turn's pacing can differ. Output is AAC in an MP4 container via macOS `afconvert`,
 * because 30 WAVs are ~7 MB and the same clips as AAC are ~1 MB. The script is macOS-only for that reason,
 * and says so rather than writing files the page cannot play.
 *
 * Usage:
 *   export GEMINI_API_KEY=…          # or GOOGLE_API_KEY
 *   node scripts/voice-samples.mjs               # render whatever is missing, then rewrite the page
 *   node scripts/voice-samples.mjs --page-only   # rewrite the page, download nothing
 *
 * It is safe to re-run: a voice already on disk is skipped, and the free tier's rate limit is retried with
 * backoff rather than failing the run.
 */
import { execFileSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'docs', 'voices')
const PAGE = join(ROOT, 'docs', 'voices.html')

/** The 30 prebuilt voices, with Google's own one-word character for each. */
const VOICES = [
  ['Zephyr', 'Bright'], ['Puck', 'Upbeat'], ['Charon', 'Informative'], ['Kore', 'Firm'],
  ['Fenrir', 'Excitable'], ['Leda', 'Youthful'], ['Orus', 'Firm'], ['Aoede', 'Breezy'],
  ['Callirrhoe', 'Easy-going'], ['Autonoe', 'Bright'], ['Enceladus', 'Breathy'], ['Iapetus', 'Clear'],
  ['Umbriel', 'Easy-going'], ['Algieba', 'Smooth'], ['Despina', 'Smooth'], ['Erinome', 'Clear'],
  ['Algenib', 'Gravelly'], ['Rasalgethi', 'Informative'], ['Laomedeia', 'Upbeat'], ['Achernar', 'Soft'],
  ['Alnilam', 'Firm'], ['Schedar', 'Even'], ['Gacrux', 'Mature'], ['Pulcherrima', 'Forward'],
  ['Achird', 'Friendly'], ['Zubenelgenubi', 'Casual'], ['Vindemiatrix', 'Gentle'],
  ['Sadachbia', 'Lively'], ['Sadaltager', 'Knowledgeable'], ['Sulafat', 'Warm'],
]

/** One sentence, written the way the assistant actually talks — so the sample sounds like a turn. */
const SAMPLE = "Hey — I've got the repository open. Want me to run the tests, or look at the diff first?"

const KEY = (process.env.GEMINI_API_KEY ?? process.env.GOOGLE_API_KEY ?? '').trim()
const PAGE_ONLY = process.argv.includes('--page-only')

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

/** Render one voice to WAV bytes, retrying the free tier's rate limit rather than failing the run. */
async function render(voice) {
  for (let attempt = 0; attempt < 6; attempt += 1) {
    const res = await fetch('https://generativelanguage.googleapis.com/v1beta/interactions', {
      method: 'POST',
      headers: { 'x-goog-api-key': KEY, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'gemini-3.8-flash-tts',
        input: [{ type: 'user_input', content: [{ type: 'text', text: SAMPLE }] }],
        response_format: { type: 'audio' },
        generation_config: { speech_config: [{ voice }] },
      }),
    })
    if (res.status === 429) {
      await sleep(5_000 * (attempt + 1))
      continue
    }
    if (!res.ok) throw new Error(`${voice}: HTTP ${res.status}`)
    const body = await res.json()
    const block = (body.steps ?? [])
      .filter((step) => step.type === 'model_output')
      .flatMap((step) => step.content ?? [])
      .filter((part) => part.type === 'audio')
      .pop()
    if (block?.data === undefined) throw new Error(`${voice}: no audio in the response`)
    return Buffer.from(block.data, 'base64')
  }
  throw new Error(`${voice}: still rate-limited after retries`)
}

/** Write the page. It lists all 30, and marks a clip that has not been rendered yet. */
async function writePage() {
  const rows = VOICES.map(([voice, character]) => `
      <tr data-voice="${voice}">
        <td class="name">${voice}</td>
        <td class="character">${character}</td>
        <td class="play">
          <button type="button" data-play="${voice}">Play</button>
          <audio id="a-${voice}" src="voices/${voice}.m4a" preload="none" controls></audio>
          <span class="missing" hidden>not rendered — run <code>node scripts/voice-samples.mjs</code></span>
        </td>
      </tr>`).join('')

  const html = `<!doctype html>
<!-- Generated by scripts/voice-samples.mjs. Edit the script, not this file. -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Gemini voices — click to hear</title>
<style>
  :root { color-scheme: dark; }
  body { font: 15px/1.5 -apple-system, system-ui, sans-serif; background: #14161a; color: #e8eaed;
         margin: 32px auto; max-width: 760px; padding: 0 20px 48px; }
  h1 { font-size: 20px; font-weight: 600; margin: 0 0 4px; }
  p.sub { color: #9aa0a6; margin: 0 0 20px; }
  table { border-collapse: collapse; width: 100%; }
  tr { border-top: 1px solid #26292e; }
  td { padding: 10px 8px; vertical-align: middle; }
  td.name { font-weight: 600; width: 150px; }
  td.character { color: #9aa0a6; width: 120px; }
  button { background: #2a2f36; color: #e8eaed; border: 1px solid #3a4048; border-radius: 6px;
           padding: 6px 14px; font-size: 14px; cursor: pointer; }
  button:hover { background: #333a42; }
  button.stop { margin-bottom: 14px; }
  audio { height: 32px; vertical-align: middle; margin-left: 8px; }
  audio[hidden], .missing[hidden] { display: none; }
  .missing { color: #9aa0a6; font-size: 13px; }
  tr.unavailable audio { display: none; }
</style>
<h1>Gemini voices</h1>
<p class="sub">${VOICES.length} prebuilt voices, one sentence, rendered by <code>gemini-3.8-flash-tts</code>.
Click a name to hear it, as often as you like. These are the voice IDs the Live session uses.</p>
<button class="stop" type="button" onclick="stopAll()">Stop all</button>
<table>${rows}
</table>
<script>
  const players = new Map()
  for (const audio of document.querySelectorAll('audio')) {
    players.set(audio.id.slice(2), audio)
    audio.addEventListener('error', () => {
      const row = audio.closest('tr')
      row.classList.add('unavailable')
      row.querySelector('.missing').hidden = false
    })
  }
  function stopAll() {
    for (const audio of players.values()) {
      audio.pause()
      audio.currentTime = 0
    }
  }
  function play(name) {
    stopAll()
    const audio = players.get(name)
    if (!audio) return
    audio.currentTime = 0
    audio.play()
  }
  for (const button of document.querySelectorAll('button[data-play]')) {
    button.addEventListener('click', () => play(button.dataset.play))
  }
</script>
`
  await writeFile(PAGE, html)
}

if (PAGE_ONLY) {
  await writePage()
  console.log(`page written: docs/voices.html`)
  process.exit(0)
}

if (KEY.length === 0) {
  console.error('no Gemini credential in the environment. Create one at https://aistudio.google.com/api-keys')
  console.error('then: export GEMINI_API_KEY=…   (or run with --page-only to rewrite the page)')
  process.exit(2)
}

let hasAfconvert = true
try {
  execFileSync('afconvert', ['-h'], { stdio: 'ignore' })
} catch {
  hasAfconvert = false
  console.error('afconvert is not available: this script is macOS-only, because it writes AAC to keep 30 clips ~1 MB')
  process.exit(2)
}

const scratch = await mkdtemp(join(tmpdir(), 'gemini-voices-'))
let failed = 0
for (const [voice] of VOICES) {
  const target = join(OUT, `${voice}.m4a`)
  if (existsSync(target)) {
    console.log(`${voice}: on disk, skipped`)
    continue
  }
  try {
    const wav = await render(voice)
    const wavPath = join(scratch, `${voice}.wav`)
    await writeFile(wavPath, wav)
    execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '48000', wavPath, target], { stdio: 'ignore' })
    console.log(`${voice}: rendered`)
    await sleep(2_500)
  } catch (error) {
    failed += 1
    console.error(`${voice}: ${error.message}`)
  }
}
await rm(scratch, { recursive: true, force: true })
await writePage()
console.log(`page written: docs/voices.html`)
process.exit(failed === 0 ? 0 : 1)
